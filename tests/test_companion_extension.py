"""Static guards for the Companion MV3 extension (local preview) + Node tests + JS->Python round trip.

The extension folder `companion/` is the PREVIEW build (validated on the real AEDB): no nativeMessaging.
The integration build (same src/, plus nativeMessaging) is generated by campus_ai.companion_build.
Only src/save.js may open a native port, and only after the student's click. Only src/open_panel.js may click
something in the page: exactly one tile link, after all of its checks.
"""
import base64
import json
import re
import shutil
import subprocess
import tempfile
import unittest
from pathlib import Path

from campus_ai import companion_protocol as cp
from campus_ai import contract

ROOT = Path(__file__).resolve().parent.parent
EXT = ROOT / 'companion'
NODE = shutil.which('node')

ALLOWED_MANIFEST_KEYS = {'manifest_version', 'name', 'version', 'description', 'minimum_chrome_version', 'key',
                         'permissions', 'action', 'content_security_policy'}

# Searched in every file the extension loads, comments included.
FORBIDDEN = [r'\beval\s*\(', r'new\s+Function', r'innerHTML', r'outerHTML', r'insertAdjacentHTML',
             r'document\.write', r'\bfetch\s*\(', r'XMLHttpRequest', r'WebSocket', r'EventSource', r'sendBeacon',
             r'importScripts', r'\bchrome\.', r'console\.', r'localStorage', r'sessionStorage', r'indexedDB',
             r'\bcaches\.', r'document\.cookie', r'\.submit\s*\(', r'requestSubmit', r'dispatchEvent',
             r'FormData', r'window\.open', r'location\.(assign|replace)\b', r'location\.href\s*=(?!=)',
             r'sendNativeMessage', r'https?://(?!ead\.aedb\.br/ava/)', r'setTimeout\s*\(\s*["\']']
NATIVE_ONLY = [r'postMessage', r'connectNative', r'\bruntime\b']     # allowed only in src/save.js


def companion_snapshot():
    data = json.loads((ROOT / 'tests' / 'fixtures' / 'contract' / 'snapshot_ficticio.json').read_text('utf-8'))
    data['events'] = []
    for table in ('courses', 'sections', 'materials', 'activities', 'announcements'):
        for rec in data[table]:
            rec['provenance']['source'] = 'companion'
    data['sources'] = [{'source': 'companion', 'last_attempt': data['generated_at'],
                        'last_success': data['generated_at'], 'status': 'parcial', 'message': ''}]
    return data


class ManifestTests(unittest.TestCase):
    def setUp(self):
        self.m = json.loads((EXT / 'manifest.json').read_text(encoding='utf-8'))

    def test_minimal_permissions_and_no_standing_access(self):
        self.assertEqual(self.m['manifest_version'], 3)
        self.assertEqual(self.m['permissions'], ['activeTab', 'scripting'])
        self.assertEqual(set(self.m) - ALLOWED_MANIFEST_KEYS, set(),
                         'no host_permissions, content_scripts, background, native messaging, web resources...')

    def test_popup_is_the_only_entry_point_and_the_csp_blocks_the_network(self):
        popup = self.m['action']['default_popup']
        self.assertTrue((EXT / popup).is_file())
        csp = self.m['content_security_policy']['extension_pages']
        for directive in ("script-src 'self'", "object-src 'none'", "connect-src 'none'", "form-action 'none'",
                          "base-uri 'none'"):
            self.assertIn(directive, csp)
        self.assertNotIn('unsafe', csp)
        self.assertNotIn('http', csp)

    def test_key_is_a_public_key_that_gives_a_stable_id(self):
        der = base64.b64decode(self.m['key'], validate=True)
        self.assertEqual(der[:2], b'\x30\x82')               # DER SubjectPublicKeyInfo, not a private key
        self.assertNotIn(b'PRIVATE', self.m['key'].encode())


class SourceGuardTests(unittest.TestCase):
    def files(self):
        return sorted((EXT / 'src').glob('*.js')) + [EXT / 'src' / 'popup.html']

    def test_no_dangerous_apis_in_loaded_code(self):
        for path in self.files():
            code = path.read_text(encoding='utf-8')
            # v0.5.4: details.js is the ONE place allowed to fetch (pinned by the next test).
            forbidden = [p for p in FORBIDDEN if not (path.name == 'details.js' and p == r'\bfetch\s*\(')]
            for pattern in forbidden + ([] if path.name == 'save.js' else NATIVE_ONLY):
                self.assertIsNone(re.search(pattern, code), f'{path.name}: {pattern}')

    def test_the_only_request_is_a_same_origin_get_of_an_activity_page(self):
        fetches = {p.name: len(re.findall(r'\bfetch\s*\(', p.read_text(encoding='utf-8'))) for p in self.files()}
        self.assertEqual({k: v for k, v in fetches.items() if v}, {'details.js': 1})
        code = (EXT / 'src' / 'details.js').read_text(encoding='utf-8')
        call = code[code.index('fetch('):]
        call = call[:call.index('});') + 3]
        self.assertIn('fetch(`/ava/mod/${kind}/view.php?id=${cmid}`, {', call)     # relative: same host only
        for option in ("method: 'GET'", "credentials: 'same-origin'", "mode: 'same-origin'", "redirect: 'manual'",
                       "cache: 'no-store'"):
            self.assertIn(option, call, option)
        self.assertIn("const KINDS = new Set(['assign', 'quiz']);", code)               # only these two pages
        self.assertLess(code.index('if (!ID.test(cmid) || !KINDS.has(kind)'), code.index('fetch('))
        self.assertLess(code.index("loc.hostname !== 'ead.aedb.br'"), code.index('fetch('))
        self.assertIn('new DOMParser().parseFromString(text', code)                      # parsed, never inserted
        for path_class in ('`course-${courseId}`', '`cmid-${cmid}`', '`path-mod-${kind}`'):
            self.assertIn(path_class, code)                                             # identity of the fetched page
        for pattern in (r'(?i)\bpost\b(?!\w)', r'\.click\s*\(', r'\.submit\s*\(', r'FormData', r'innerHTML',
                        r'\.value\s*=', r'setAttribute', r'\bsesskey\b', r'document\.cookie', r'startattempt',
                        r'processattempt', r'\.append\(', r'appendChild'):
            self.assertIsNone(re.search(pattern, code), pattern)
        sync = (EXT / 'src' / 'sync.js').read_text(encoding='utf-8')
        self.assertEqual(sync.count("files: ['src/details.js']"), 1)
        popup = (EXT / 'src' / 'popup.js').read_text(encoding='utf-8')
        self.assertIn('details: true', popup)
        self.assertIn('details: true', (EXT / 'src' / 'course_sync.js').read_text(encoding='utf-8'))

    def test_only_these_extension_api_calls_exist(self):
        used = set()
        for path in (EXT / 'src').glob('*.js'):
            used |= set(re.findall(r'\bapi\.[A-Za-z]+\.[A-Za-z]+', path.read_text(encoding='utf-8')))
        self.assertEqual(used, {'api.tabs.query', 'api.scripting.executeScript', 'api.runtime.connectNative',
                                'api.runtime.lastError'})
        popup = (EXT / 'src' / 'popup.js').read_text(encoding='utf-8')
        rest = re.sub(r'\(chrome[,)]', '(', popup)          # the API object is only ever passed as an argument
        self.assertEqual(re.findall(r'\bchrome\b', rest), [])

    def test_popup_page_has_one_local_module_script_and_no_inline_code(self):
        html = (EXT / 'src' / 'popup.html').read_text(encoding='utf-8')
        self.assertEqual(re.findall(r'<script\b[^>]*>', html), ['<script type="module" src="popup.js">'])
        self.assertIsNone(re.search(r'\son[a-z]+\s*=', html))
        self.assertIsNone(re.search(r'<(form|iframe|object|embed|img|link rel="stylesheet" href="http)', html))

    def test_page_data_is_rendered_only_as_text(self):
        render = (EXT / 'src' / 'render.js').read_text(encoding='utf-8')
        self.assertIn('document.createTextNode', render)
        self.assertEqual(re.findall(r'setAttribute\(', render), ['setAttribute('])   # the single, fixed-name helper

    def test_the_only_clicks_are_the_tile_link_and_the_x_of_the_authorized_window(self):
        # v0.5.2 (authorized by the student on 09/11/2026): exactly TWO clicks in the whole extension, both in
        # open_panel.js: the verified tile link, and the X of the "Preferência dos dados" window. Each one after all
        # of its gates, with nothing after it. Never "Sim"/"Cancelar", never another dialog.
        clicks = {p.name: len(re.findall(r'\.click\s*\(', p.read_text(encoding='utf-8'))) for p in self.files()}
        self.assertEqual({k: v for k, v in clicks.items() if v}, {'open_panel.js': 2})
        code = (EXT / 'src' / 'open_panel.js').read_text(encoding='utf-8')
        self.assertEqual(re.findall(r'\w+\.click\s*\(', code), ['link.click(', 'button.click('])
        tile, closer = code.split('function closeDataPreference(')
        click = tile.index('link.click()')
        for gate in ("'curso_diferente'", "'formato'", "'pagina_invalida'", "'dialogo_bloqueia'", "'tile_ambiguo'",
                     "'tile_perigoso'", "'tile_sem_vinculo'", "'tile_nao_clicavel'", "'tile_oculto'",
                     "'/ava/course/section.php'", 'DANGEROUS.some'):
            self.assertLess(tile.index(gate), click, gate)
        self.assertEqual(tile[click:].count('return'), 1)            # nothing else happens after the tile click
        x = closer.index('button.click()')
        for gate in ("'parametros_invalidos'", "'curso_diferente'", "'formato'", "'/ava/course/view.php'",
                     'dataPreferenceClose(doc)', "'dialogo_nao_identificado'", 'isConnected', 'rendered(button)'):
            self.assertLess(closer.index(gate), x, gate)
        self.assertEqual(closer[x:closer.index('Object.defineProperty')].count('return'), 1)   # nothing after the X
        self.assertNotRegex(closer, r'(?i)sim|cancelar|save|cancel')  # it never names (or looks for) the other buttons
        sync = (EXT / 'src' / 'sync.js').read_text(encoding='utf-8')
        self.assertNotIn('connectNative', sync)                      # sync never opens a native port itself
        self.assertEqual(sync.count("files: ['src/open_panel.js']"), 1)
        self.assertEqual(sync.count('clickTile('), 2)                # its definition and its single call
        self.assertEqual(sync.count('closeDialog('), 2)              # idem

    def test_the_preference_window_is_recognised_by_fixed_markers_and_any_other_dialog_blocks(self):
        dom = (EXT / 'src' / 'dom_tiles.js').read_text(encoding='utf-8')
        panel = (EXT / 'src' / 'open_panel.js').read_text(encoding='utf-8')
        dialogs = "const DIALOGS = '[role=\"dialog\"], [role=\"alertdialog\"], .modal, dialog[open]';"
        self.assertIn(dialogs, dom)
        self.assertIn(dialogs, panel)                                # both files block on the same dialogs
        self.assertIn("title: 'preferencia dos dados', buttons: Object.freeze(['cancelar', 'sim'])", dom)
        for marker in ("'.modal-header, [data-region=\"header\"]'", 'inHeader.length === 1', 'others.length === 2',
                       '!dialog.querySelector(FIELDS)', "dialogs.visible.length !== 1"):
            self.assertIn(marker, dom, marker)
        self.assertNotRegex(dom, r'\.click\s*\(')                   # the reader only recognises; it never clicks
        preview = (EXT / 'src' / 'preview.js').read_text(encoding='utf-8')
        for key in ('hiddenDialogs', 'dataPreferenceDialogs', 'unknownDialogs', 'sectionVisible'):
            self.assertIn(f"'{key}'", preview)                       # the diagnostic keeps them after cleaning

    def test_neither_mode_saves_before_the_explicit_click(self):
        # v0.5.2: "Sincronizar disciplina" waits for "Salvar no Campus AI".
        popup = (EXT / 'src' / 'popup.js').read_text(encoding='utf-8')
        call = popup[popup.index('await runSync(chrome'):]
        self.assertIn('autoSave: false', call[:call.index('});')])
        # v0.5.3: "Sincronizar seções autorizadas" reads only; saving is createCourseSaver, handed to the button.
        course = (EXT / 'src' / 'course_sync.js').read_text(encoding='utf-8')
        reading, saving = course.split('export function createCourseSaver(')
        reading = reading.split('export async function runCourseSync(')[1]
        self.assertIn('autoSave: false', reading)
        self.assertNotRegex(reading, r'\bsave\s*\(|saveSnapshot\s*\(|connectNative')   # no save in the read phase
        self.assertIn('if (!running) running = commit();', saving)                      # single flight
        self.assertIn('createCourseSaver(chrome, readings', popup)
        self.assertIn('renderCourseOutcome(progress, result, outcome, { onSave })', popup)
        self.assertNotIn('createCourseSaver(chrome, readings, { notRead: outcome.sections.length - readings.length })()', popup)
        render = (EXT / 'src' / 'render.js').read_text(encoding='utf-8')
        handler = render[render.index("button.addEventListener('click', async () => {"):]
        self.assertLess(handler.index('button.disabled = true;'), handler.index('onSave()'))   # no double click

    def test_section_authorization_cannot_be_widened_from_the_popup(self):
        popup = (EXT / 'src' / 'popup.js').read_text(encoding='utf-8')
        self.assertNotIn('authorizedSections', popup)        # only the constant in preview.js decides
        preview = (EXT / 'src' / 'preview.js').read_text(encoding='utf-8')
        self.assertIn("export const AUTHORIZED_SECTIONS = Object.freeze(['atividades avaliativas']);", preview)
        catalog_js = (EXT / 'src' / 'tiles_catalog.js').read_text(encoding='utf-8')
        self.assertNotRegex(catalog_js, r'\.click\s*\(|textContent\s*=|setAttribute|\.href\s*=(?!=)')

    def test_preview_build_has_no_native_messaging_and_saving_waits_for_a_click(self):
        self.assertNotIn('nativemessaging', (EXT / 'manifest.json').read_text(encoding='utf-8').lower())
        self.assertFalse((EXT / 'native').exists())
        popup = (EXT / 'src' / 'popup.js').read_text(encoding='utf-8')
        # the save function is only handed to the renderer, which calls it from the button's click handler
        self.assertIn("model.state === 'ok' ? () => saveSnapshot(", popup)
        render = (EXT / 'src' / 'render.js').read_text(encoding='utf-8')
        self.assertIn("button.addEventListener('click', async () => {", render)
        self.assertEqual(render.count('onSave()'), 1)

    def test_constants_match_python(self):
        js = (EXT / 'src' / 'protocol.js').read_text(encoding='utf-8')
        self.assertIn(f"PROTOCOL_ID = '{cp.PROTOCOL_ID}'", js)
        self.assertIn(f"HOST_NAME = '{cp.HOST_NAME}'", js)
        self.assertIn('MAX_MESSAGE_BYTES = 512 * 1024', js)
        self.assertEqual(cp.MAX_MESSAGE_BYTES, 512 * 1024)
        for kind, route in cp.REPORTABLE_PAGES.items():
            self.assertIn(f"{kind}: '{route}'", js)

    def test_activity_kinds_match_contract(self):
        js = (EXT / 'src' / 'classify.js').read_text(encoding='utf-8')
        block = re.search(r'const ACTIVITY = new Set\(\[(.*?)\]\)', js, re.S).group(1)
        self.assertEqual(set(re.findall(r"'([a-z0-9]+)'", block)), set(contract.ACTIVITY_KINDS))


@unittest.skipUnless(NODE, 'Node.js não encontrado; testes JS da extensão ignorados')
class NodeTests(unittest.TestCase):
    def test_js_unit_tests(self):
        files = sorted(str(f) for f in (EXT / 'test').glob('*.test.mjs'))
        self.assertTrue(files)
        proc = subprocess.run([NODE, '--test', *files], capture_output=True, text=True, encoding='utf-8',
                              errors='replace', timeout=120, cwd=ROOT)
        self.assertEqual(proc.returncode, 0, proc.stdout[-3000:] + proc.stderr[-3000:])

    def test_python_host_accepts_js_messages(self):
        with tempfile.TemporaryDirectory(dir=ROOT / '.tmp-campus-ai') as tmp:
            snap_path = Path(tmp) / 'snap.json'
            snap_path.write_text(json.dumps(companion_snapshot()), encoding='utf-8')
            token = 'd' * 32
            proc = subprocess.run([NODE, str(EXT / 'test' / 'emit_messages.mjs'), str(snap_path), token],
                                  capture_output=True, text=True, encoding='utf-8', timeout=60, cwd=ROOT)
        self.assertEqual(proc.returncode, 0, proc.stderr[-2000:])
        received = []
        session = cp.CompanionSession({'7653'}, received.append, token_factory=lambda: token)
        replies = [session.handle(line.encode('utf-8')) for line in proc.stdout.splitlines() if line]
        self.assertEqual([r['type'] for r in replies], ['welcome', 'ack'], replies)
        self.assertEqual(len(received), 1)


